import { defineConfig, type Options } from 'tsup';

// JS bundles for the Go module (see README_GO.md): Go package under pkg/ → TS entry it wraps.
// Each becomes pkg/<package>/bundle/bundle.js, which that package embeds and runs with goja.
const goBundles: Record<string, string> = {
  fhirparser: 'src/fhir/parser/index.ts',
  guard: 'src/go/guard.ts',
};

// goja has no module system, so each bundle is a self-contained IIFE that exposes its exports
// as the global `Exports` (jsbundle.GlobalName in pkg/internal/jsbundle), and es2017 is the language
// level goja supports. The output is committed (Go modules are fetched from git, so it can't
// live in the ignored dist/); CI fails if it is out of date. Left unminified so changes show up
// readably in PR diffs.
const goBundle = (pkg: string, entry: string): Options => ({
  entry: { bundle: entry },
  outDir: `pkg/${pkg}/bundle`,
  format: ['iife'],
  globalName: 'Exports',
  target: 'es2017',
  platform: 'neutral',
  outExtension: () => ({ js: '.js' }), // tsup's default for iife would be .global.js
  dts: false,
  sourcemap: false,
  splitting: false,
  clean: false, // outDir is inside a Go package directory — never wipe it
  banner: {
    js: `// GENERATED by \`yarn build\` (tsup.config.ts) from ${entry} — do not edit by hand.`,
  },
});

export default defineConfig([
  {
    // `index` is the main barrel (fhirpath-free, grpc-modules-free). `fhirpath` is a separate subpath
    // entry (`@d4l/collect-lib/fhirpath`) so the fhirpath.js engine is loaded only where expressions
    // are evaluated (phoenix; Studio's synthetic-data generator), not on every page that imports the
    // barrel. See the note in src/fhir/enable-when-eval.ts. `fhir-to-questions` is the same idea for
    // the shared FHIR->proto Question parser (src/fhir/parser/).
    entry: {
      index: 'src/index.ts',
      fhirpath: 'src/fhir/enable-when-eval.ts',
      'fhir-to-questions': 'src/fhir/parser/index.ts',
    },
    format: ['cjs', 'esm'], // Build for commonJS and ESmodules
    dts: true, // Generate declaration file (.d.ts)
    splitting: true,
    sourcemap: true,
    clean: true,
    platform: 'browser',
  },
  ...Object.entries(goBundles).map(([pkg, entry]) => goBundle(pkg, entry)),
]);
