// postalCodeQuestionnaire has one postal_code item in language with the given country sources;
// pccs-1 requires exactly one.
func postalCodeQuestionnaire(language string, fromItems ...string) fhir5.Questionnaire {
	name, version, text := "q", "1", "Postal code"
	system, code := "http://fhir.data4life.care/r5/CodeSystem/custom-question-class", "postal_code"
	item := fhir5.QuestionnaireItem{LinkId: "zip", Text: &text, Type: "string"}
	item.Extension = []common.Extension{{
		URL:                  "http://hl7.org/fhir/StructureDefinition/questionnaire-itemControl",
		ValueCodeableConcept: &common.CodeableConcept{Coding: []common.Coding{{System: &system, Code: &code}}},
	}}
	for _, fromItem := range fromItems {
		item.Extension = append(item.Extension, common.Extension{
			URL: "http://fhir.data4life.care/fhir/StructureDefinition/postalcode-country-source",
			Extension: []common.Extension{{
				URL:         "fromItem",
				ValueString: &fromItem,
			}},
		})
	}
	return fhir5.Questionnaire{
		ResourceType: "Questionnaire",
		Name:         &name,
		Version:      &version,
		Language:     &language,
		Status:       fhir5.PublicationStatusActive,
		Item:         []fhir5.QuestionnaireItem{item},
	}
}

func TestParse_InvalidInput(t *testing.T) {
	tests := []struct {
		name    string
		input   map[string]fhir5.Questionnaire
		message string
	}{
		{"no languages", map[string]fhir5.Questionnaire{}, "no languages"},
		{
			"missing name and version",
			map[string]fhir5.Questionnaire{"en": {ResourceType: "Questionnaire"}},
			"missing required fields (name, version)",
		},
		{
			"postal code without country source",
			map[string]fhir5.Questionnaire{"en": postalCodeQuestionnaire("en")},
			"Question zip: postal_code countrySource must include exactly one of fromItem or fixedCountry",
		},
		{
			"postal code without country source in a later language",
			map[string]fhir5.Questionnaire{
				"de": postalCodeQuestionnaire("de", "country"),
				"en": postalCodeQuestionnaire("en"),
			},
			"Question zip: postal_code countrySource must include exactly one of fromItem or fixedCountry (language en)",
		},
		{
			"postal code with two country sources in a later language",
			map[string]fhir5.Questionnaire{
				"de": postalCodeQuestionnaire("de", "country"),
				"en": postalCodeQuestionnaire("en", "country", "region"),
			},
			"(language en)",
		},
		{
			"postal code with different country sources between languages",
			map[string]fhir5.Questionnaire{
				"de": postalCodeQuestionnaire("de", "country"),
				"en": postalCodeQuestionnaire("en", "region"),
			},
			"Question zip: postal_code countrySource differs between languages de and en",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := fhirquestionnaire.Parse(tt.input)
			if !errors.Is(err, fhirquestionnaire.ErrInvalidQuestionnaire) {
				t.Fatalf("want ErrInvalidQuestionnaire, got %v", err)
			}
			if !strings.Contains(err.Error(), tt.message) {
				t.Errorf("error %q does not mention %q", err, tt.message)
			}
		})
	}
}

func TestParse_PostalCodeInEveryLanguage(t *testing.T) {
	pq, err := fhirquestionnaire.Parse(map[string]fhir5.Questionnaire{
		"de": postalCodeQuestionnaire("de", "country"),
		"en": postalCodeQuestionnaire("en", "country"),
	})
	if err != nil {
		t.Fatal(err)
	}
	got := pq.GetQuestions()[0].GetConfig().AsMap()["countrySource"]
	if want := map[string]any{"fromItem": "country"}; !reflect.DeepEqual(got, want) {
		t.Errorf("countrySource = %v, want %v", got, want)
	}
}

// Parsing logs and skips items it can't convert (console.warn in TS). In goja that only works
// because jsbundle provides console; without it the warning itself would throw.
func TestParse_SkipsUnsupportedItem(t *testing.T) {
	name, version, text := "q", "1", "Text"
	input := map[string]fhir5.Questionnaire{"en": {
		ResourceType: "Questionnaire",
		Name:         &name,
		Version:      &version,
		Item: []fhir5.QuestionnaireItem{
			{LinkId: "unsupported", Type: "attachment", Text: &text},
			{LinkId: "kept", Type: "string", Text: &text},
		},
	}}
	got, err := fhirquestionnaire.Parse(input)
	if err != nil {
		t.Fatal(err)
	}
	if len(got.Questions) != 1 || got.Questions[0].LinkId != "kept" {
		t.Errorf("want only question %q, got %v", "kept", got.Questions)
	}
}

// A runtime that saw a failing call must still work afterwards (it goes back to the pool).
func TestParse_RecoversAfterError(t *testing.T) {
	if _, err := fhirquestionnaire.Parse(map[string]fhir5.Questionnaire{"en": {}}); err == nil {
		t.Fatal("want error")
	}
	if _, err := fhirquestionnaire.Parse(fixtureSets[0].questionnaires(t)); err != nil {
		t.Fatal(err)
	}
}

// Run with -race: runtimes are pooled and must never be shared between goroutines.
func TestConcurrent(t *testing.T) {
	input := fixtureSets[0].questionnaires(t)
	definition := fixtureSets[0].definition(t)
	wantParsed, err := fhirquestionnaire.Parse(input)
	if err != nil {
		t.Fatal(err)
	}
	wantGenerated, err := fhirquestionnaire.Generate(definition, fixtureOptions)
	if err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	for range 8 {
		wg.Go(func() {
			got, err := fhirquestionnaire.Parse(input)
			if err != nil {
				t.Error(err)
				return
			}
			if !proto.Equal(got, wantParsed) {
				t.Error("concurrent Parse result differs")
			}
		})
		wg.Go(func() {
			got, err := fhirquestionnaire.Generate(definition, fixtureOptions)
			if err != nil {
				t.Error(err)
				return
			}
			if !reflect.DeepEqual(got, wantGenerated) {
				t.Error("concurrent Generate result differs")
			}
		})
	}
	wg.Wait()
}

// The bundle is compiled against @d4l/grpc-modules from package.json and its proto JSON is
// exchanged with the Go types of github.com/d4l-data4life/grpc-modules from go.mod. Both are cut
// from the same repo and tag, so they must be the same version, or the two sides may disagree
// on fields.
func TestGrpcModulesVersionsMatch(t *testing.T) {
	pkgJSON, err := os.ReadFile(filepath.Join(repoRoot, "package.json"))
	if err != nil {
		t.Fatal(err)
	}
	var pkg struct {
		Dependencies map[string]string `json:"dependencies"`
	}
	if err := json.Unmarshal(pkgJSON, &pkg); err != nil {
		t.Fatal(err)
	}
	npmVersion := pkg.Dependencies["@d4l/grpc-modules"]
	if !regexp.MustCompile(`^\d+\.\d+\.\d+$`).MatchString(npmVersion) {
		t.Fatalf("package.json must pin @d4l/grpc-modules to an exact version, got %q", npmVersion)
	}

	goMod, err := os.ReadFile(filepath.Join(repoRoot, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	m := regexp.MustCompile(`(?m)^\s*(?:require\s+)?github\.com/d4l-data4life/grpc-modules\s+(v\S+)`).FindSubmatch(goMod)
	if m == nil {
		t.Fatal("go.mod does not require github.com/d4l-data4life/grpc-modules")
	}
	if goVersion := string(m[1]); goVersion != "v"+npmVersion {
		t.Errorf("grpc-modules versions differ: package.json %s, go.mod %s — run "+
			"`go get github.com/d4l-data4life/grpc-modules@v%s`", npmVersion, goVersion, npmVersion)
	}
}

