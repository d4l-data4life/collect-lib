import { Questionnaire } from '@d4l/grpc-modules/research-pillars';
import * as fs from 'fs';
import * as path from 'path';
import { generateFHIRQuestionnaire, parseFHIRQuestionnaire } from '../questionnaire';

const loadFixture = (name: string) =>
  JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures', name), 'utf-8'));

// Deep JSON equality: what goes over the wire, so undefined fields and key order do not count.
const asJSON = (value: unknown) => JSON.parse(JSON.stringify(value));

// The environment the fixtures were generated for.
const OPTIONS = {
  baseUrl: 'https://collect.dev.d4l-dev.de/fhir/r5',
  staticUrl: 'https://collect.dev.d4l-dev.de/api/static',
  programName: 'import_questionnaire',
  languages: ['en', 'de'],
  date: '2026-11-09T12:23:30Z',
  timestamp: '2026-11-10T06:37:58Z',
};

// questionnaire_*: a real questionnaire generated by Research Studio.
// edge-cases_*: hand-built cases for code systems, Enable Behavior and matrices.
describe.each([
  ['studio questionnaire', 'questionnaire', 'expected-questionnaire.json'],
  ['edge cases', 'edge-cases', 'expected-edge-cases.json'],
])('Round Trip (%s)', (_, prefix, expectedName) => {
  const fixtures = { en: loadFixture(`${prefix}_en.json`), de: loadFixture(`${prefix}_de.json`) };
  const expected = loadFixture(expectedName);

  it('Parsing yields the expected Questionnaire Definition', () => {
    expect(asJSON(parseFHIRQuestionnaire(fixtures))).toStrictEqual(expected);
  });

  it('Generation yields the FHIR Questionnaire of each language', () => {
    expect(asJSON(generateFHIRQuestionnaire(expected, OPTIONS))).toStrictEqual(fixtures);
  });

  // Canonical proto JSON, as Go's protojson writes it: default fields omitted, enums as names.
  it('Generation accepts the definition as proto JSON', () => {
    const protoJSON = Questionnaire.toJSON(Questionnaire.fromJSON(expected)) as Questionnaire;
    expect(asJSON(generateFHIRQuestionnaire(protoJSON, OPTIONS))).toStrictEqual(fixtures);
  });
});
